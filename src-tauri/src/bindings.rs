use crate::errors::{ApiError, ErrorCode, ErrorKind};
use crate::profiles::Profile;
use crate::tasks::{CarryOverRule, NewTask, Task, TaskPlacement, TaskStatus};

/// Renders the contents of `src/api/bindings.ts` from every IPC-facing type.
/// Written by `cargo run --bin export-bindings`; freshness is asserted in tests.
pub fn typescript() -> String {
    let conf =
        specta::ts::ExportConfiguration::new().bigint(specta::ts::BigIntExportBehavior::Number);
    let mut out = String::from("// This file has been generated by Specta. DO NOT EDIT.\n\n");
    // IPC-facing types — extend as new entities cross the boundary.
    let types = [
        specta::ts::export::<Profile>(&conf).expect("export Profile"),
        specta::ts::export::<Task>(&conf).expect("export Task"),
        specta::ts::export::<NewTask>(&conf).expect("export NewTask"),
        specta::ts::export::<TaskStatus>(&conf).expect("export TaskStatus"),
        specta::ts::export::<CarryOverRule>(&conf).expect("export CarryOverRule"),
        specta::ts::export::<TaskPlacement>(&conf).expect("export TaskPlacement"),
        specta::ts::export::<ApiError>(&conf).expect("export ApiError"),
        specta::ts::export::<ErrorCode>(&conf).expect("export ErrorCode"),
        specta::ts::export::<ErrorKind>(&conf).expect("export ErrorKind"),
    ];
    out.push_str(&types.join("\n"));
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bindings_ts_is_up_to_date() {
        let on_disk = std::fs::read_to_string("../src/api/bindings.ts")
            .expect("bindings.ts missing — run cargo run --bin export-bindings");
        assert_eq!(
            on_disk,
            typescript(),
            "bindings.ts is stale — run cargo run --bin export-bindings"
        );
    }
}
