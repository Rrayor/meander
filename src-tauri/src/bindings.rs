use crate::profiles::Profile;

/// Renders the contents of `src/api/bindings.ts` from every IPC-facing type.
/// Written by `cargo run --bin export-bindings`; freshness is asserted in tests.
pub fn typescript() -> String {
    let conf =
        specta::ts::ExportConfiguration::new().bigint(specta::ts::BigIntExportBehavior::Number);
    let mut out = String::from("// This file has been generated by Specta. DO NOT EDIT.\n\n");
    // IPC-facing types — extend as new entities cross the boundary.
    let types = [specta::ts::export::<Profile>(&conf).expect("export Profile")];
    out.push_str(&types.join("\n"));
    out.push('\n');
    out
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn bindings_ts_is_up_to_date() {
        let on_disk = std::fs::read_to_string("../src/api/bindings.ts")
            .expect("bindings.ts missing — run cargo run --bin export-bindings");
        assert_eq!(
            on_disk,
            typescript(),
            "bindings.ts is stale — run cargo run --bin export-bindings"
        );
    }
}
